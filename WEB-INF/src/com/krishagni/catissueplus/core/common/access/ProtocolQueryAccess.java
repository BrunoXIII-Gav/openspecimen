package com.krishagni.catissueplus.core.common.access;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.function.Predicate;
import java.util.regex.Pattern;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;

import org.w3c.dom.Element;
import org.w3c.dom.Node;

import edu.common.dynamicextensions.query.QueryParser;
import edu.common.dynamicextensions.query.ast.ExpressionNode;
import edu.common.dynamicextensions.query.ast.FieldNode;
import edu.common.dynamicextensions.query.ast.FilterExpressionNode;
import edu.common.dynamicextensions.query.ast.FilterNode;
import edu.common.dynamicextensions.query.ast.FilterNode.RelationalOp;
import edu.common.dynamicextensions.query.ast.FilterNodeMarker;
import edu.common.dynamicextensions.query.ast.QueryExpressionNode;

/** Checks actual AQL fields, including predicates, ordering and nested queries. */
public final class ProtocolQueryAccess {

	private static final Set<String> NATIVE_FIELDS = loadNativeFields();

	// Exact metadata-only SQL generated by BiospecimenDaoHelper for an all-sites assignment.
	// Do not allow arbitrary SQL, even when the left-hand field is a permitted native field.
	private static final Pattern INSTITUTE_SITE_IDS = Pattern.compile(
		"\"select identifier from catissue_site where institute_id = [1-9][0-9]* and activity_status != 'Disabled'\"");
	private static final Set<String> SITE_ID_FIELDS = Set.of(
		"CollectionProtocol.cpSites.siteId", "Participant.medicalRecord.mrnSiteId");

	private ProtocolQueryAccess() { }

	public static boolean isNativeField(String name) {
		return NATIVE_FIELDS.contains(name);
	}

	public static boolean permits(String aql, Predicate<String> fieldAllowed) {
		try { return permits(new QueryParser(aql).getQueryAst(), fieldAllowed); }
		catch (RuntimeException malformed) { return false; }
	}

	private static boolean permits(QueryExpressionNode query, Predicate<String> allowed) {
		if (query == null || query.hasResultPostProc()) return false;
		if (query.getSelectList() != null && query.getSelectList().getElements().stream().anyMatch(expr -> !permits(expr, allowed))) return false;
		if (!permits(query.getFilterExpr(), allowed) || !permits(query.getHavingExpr(), allowed)) return false;
		return query.getOrderExpr() == null || query.getOrderExpr().getExprs().stream().allMatch(order -> permits(order.getExpr(), allowed));
	}

	private static boolean permits(ExpressionNode expression, Predicate<String> allowed) {
		return expression == null || expression.getFields().stream().allMatch(field -> allowed.test(field.getName()));
	}

	private static boolean permits(FilterNodeMarker filter, Predicate<String> allowed) {
		if (filter == null) return true;
		if (filter instanceof FilterExpressionNode expression) return expression.getOperands().stream().allMatch(operand -> permits(operand, allowed));
		if (!(filter instanceof FilterNode condition)) return false;
		if (condition.getSql() != null && !condition.getSql().isBlank() && !isInstituteSiteFilter(condition)) return false;
		return permits(condition.getLhs(), allowed) && permits(condition.getRhs(), allowed) &&
			(condition.getSubQuery() == null || permits(condition.getSubQuery(), allowed));
	}

	private static boolean isInstituteSiteFilter(FilterNode condition) {
		return condition.getRelOp() == RelationalOp.IN && condition.getLhs() instanceof FieldNode field &&
			SITE_ID_FIELDS.contains(field.getName()) && INSTITUTE_SITE_IDS.matcher(condition.getSql()).matches() &&
			condition.getRhs() == null && condition.getSubQuery() == null;
	}

	private static Set<String> loadNativeFields() {
		Set<String> fields = new HashSet<>();
		try {
			DocumentBuilderFactory factory = DocumentBuilderFactory.newDefaultInstance();
			factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
			factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_DTD, "");
			factory.setAttribute(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "");
			for (String file : List.of("cp.xml", "cpr.xml", "scg.xml", "specimen.xml", "specimen-kit.xml")) {
				try (var input = ProtocolQueryAccess.class.getResourceAsStream("/query-forms/" + file)) {
					if (input == null) throw new IllegalStateException("Missing native query form: " + file);
					String template = new String(input.readAllBytes(), StandardCharsets.UTF_8);
					// Leading Velocity macros are not part of the XML document.
					String xml = template.substring(template.indexOf("<form>"));
					Element root = factory.newDocumentBuilder().parse(new ByteArrayInputStream(xml.getBytes(StandardCharsets.UTF_8))).getDocumentElement();
					Element view = child(root, "view");
					readFields(view, text(view, "name"), fields);
				}
			}
			return Set.copyOf(fields);
		} catch (Exception exception) {
			throw new IllegalStateException("Could not load native query field definitions", exception);
		}
	}

	private static void readFields(Element view, String prefix, Set<String> fields) {
		for (Node row = view.getFirstChild(); row != null; row = row.getNextSibling()) {
			if (!(row instanceof Element element) || !element.getTagName().equals("row")) continue;
			for (Node item = row.getFirstChild(); item != null; item = item.getNextSibling()) {
				if (!(item instanceof Element control)) continue;
				String name = text(control, "name");
				String udn = text(control, "udn");
				if (name == null || Set.of("extensions", "customFields").contains(name)) continue;
				for (String alias : udn == null || udn.equals(name) ? List.of(name) : List.of(name, udn)) {
					String path = prefix + "." + alias;
					if (control.getTagName().equals("subForm")) {
						Element nested = child(control, "view");
						readFields(nested == null ? control : nested, path, fields);
					} else {
						fields.add(path);
					}
				}
			}
		}
	}

	private static Element child(Element parent, String tag) {
		for (Node item = parent.getFirstChild(); item != null; item = item.getNextSibling()) {
			if (item instanceof Element element && element.getTagName().equals(tag)) return element;
		}
		return null;
	}

	private static String text(Element parent, String tag) {
		Element element = child(parent, tag);
		return element == null ? null : element.getTextContent().trim();
	}
}
